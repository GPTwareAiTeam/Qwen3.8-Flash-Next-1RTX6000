"""
Greedy identity and next-token KL: the lossless / quality gate used for every change in the README.

    # record a run against a running server (identity: 8 prompts x 128 tokens; KL: 16 short + 9 long prompts)
    BASE_URL=http://127.0.0.1:5000 API_KEY=... python bench/identity_kl.py run --out runA.json [--short-only]
    # compare two runs (e.g. two boots of the same build give the noise floor; then baseline vs candidate)
    python bench/identity_kl.py compare runA.json runB.json

`run` records, per identity prompt, the greedy text and the emitted token sequence; per KL prompt, the top-20
next-token log-probabilities. The 9 long prompts (~8.7k / 35k / 157k tokens) are generated by `common.py` from
fixed seed texts, so they are identical on every machine; they need a server with `max_seq_len` >= 160k.

`compare` prints identity (text and tokens, n/8) and KL(A||B) over A's top-20 (both renormalised over that support;
tokens missing from B are floored at B's minimum minus 2 nats), mean and max separately for the short and the long
prompts, plus top-1 agreement.

Run against a server with no other traffic: with other requests in the batch, greedy text can change at near-tie
tokens (batch-dependent numerics), so identity is only meaningful on an otherwise idle server, fresh after the
launcher's warm-up. KL is robust to this (0.0000 short-context between two runs on a busy server).
"""
import argparse
import json
import math
import sys

from common import IDENTITY, long_kl_prompts, post, short_kl_prompts


def run(out: str, short_only: bool):
    res = {"identity_text": [], "identity_tokens": [], "kl": []}
    for p in IDENTITY:
        _, d = post({"prompt": p, "max_tokens": 128, "loop_detect_window": 0, "logprobs": 1})
        c = d["choices"][0]
        res["identity_text"].append(c["text"])
        res["identity_tokens"].append((c.get("logprobs") or {}).get("tokens") or [])
    prompts = [("short", p) for p in short_kl_prompts()] + ([] if short_only else [("long", p) for p in long_kl_prompts()])
    for kind, p in prompts:
        _, d = post({"prompt": p, "max_tokens": 1, "logprobs": 20, "top_logprobs": 20, "loop_detect_window": 0})
        lp = d["choices"][0].get("logprobs") or {}
        res["kl"].append(dict(kind = kind, ptok = d["usage"]["prompt_tokens"],
                              top = (lp.get("top_logprobs") or [None])[0]))
        print(f"{kind} {d['usage']['prompt_tokens']} tokens", file = sys.stderr, flush = True)
    json.dump(res, open(out, "w"))
    print(f"wrote {out}")


def kl(p: dict, q: dict):
    if not p or not q:
        return None
    floor = min(q.values()) - 2
    zp = math.log(sum(math.exp(v) for v in p.values()))
    qs = {t: q.get(t, floor) for t in p}
    zq = math.log(sum(math.exp(v) for v in qs.values()))
    return sum(math.exp(v - zp) * ((v - zp) - (qs[t] - zq)) for t, v in p.items())


def compare(a: str, b: str):
    A, B = json.load(open(a)), json.load(open(b))
    same_text = sum(x == y for x, y in zip(A["identity_text"], B["identity_text"]))
    same_tok = sum(x == y for x, y in zip(A["identity_tokens"], B["identity_tokens"]))
    print(f"identity: text {same_text}/{len(A['identity_text'])}, tokens {same_tok}/{len(A['identity_tokens'])}")
    for kind in ("short", "long"):
        ks, top1 = [], 0
        rows = [(x, y) for x, y in zip(A["kl"], B["kl"]) if x["kind"] == kind]
        for x, y in rows:
            k = kl(x["top"], y["top"])
            if k is not None:
                ks.append(k)
            if x["top"] and y["top"] and max(x["top"], key = x["top"].get) == max(y["top"], key = y["top"].get):
                top1 += 1
        if rows:
            print(f"KL {kind}: n={len(ks)} mean={sum(ks) / max(1, len(ks)):.4f} max={max(ks, default = 0):.4f} "
                  f"top-1 agree {top1}/{len(rows)}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest = "cmd", required = True)
    r = sub.add_parser("run"); r.add_argument("--out", required = True); r.add_argument("--short-only", action = "store_true")
    c = sub.add_parser("compare"); c.add_argument("a"); c.add_argument("b")
    args = ap.parse_args()
    run(args.out, args.short_only) if args.cmd == "run" else compare(args.a, args.b)
